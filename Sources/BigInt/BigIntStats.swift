    case MBI_SET_DIV_BI_FASTPATH
    case MBI_SET_DIV_64_KNUTH
    case MBI_SET_DIV_BI_KNUTH
    case MBI_SET_REM_PRIMITIVE
    case MBI_SET_REM_BI_FASTPATH
    case MBI_SET_REM_BI_KNUTH
    case MBI_SET_MOD_PRIMITIVE
    case MBI_SET_MOD_BI_FASTPATH
    case MBI_SET_MOD_BI_KNUTH
    case MBI_ADD_SQR_PRIMITIVE
    case MBI_ADD_SQR_BI
    case MBI_SET_BITWISE_OP
