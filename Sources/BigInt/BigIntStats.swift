    case BI_MUL_BI
    case BI_MUL_PRIMITIVE
    case BI_DIV_BI
    case BI_DIV_PRIMITIVE
    case BI_REM_BI
    case BI_REM_PRIMITIVE
    case BI_MOD_BI
    case BI_MOD_PRIMITIVE
    case BI_DIV_INVERSE_PRIMITIVE
    case BI_REM_INVERSE_PRIMITIVE
    case BI_MOD_INVERSE_PRIMITIVE
    case BI_SQR
    case BI_POW
    case BI_BITWISE_OP

    case MBI_CONSTRUCT_EMPTY
    case MBI_CONSTRUCT_PRIMITIVE
    case MBI_CONSTRUCT_BI
    case MBI_CONSTRUCT_CAPACITY_HINT

    case MBI_SET_ADD_SUB_PRIMITIVE
    case MBI_SET_ADD_SUB_BI
    case MBI_SET_MUL_PRIMITIVE
    case MBI_SET_MUL_BI
