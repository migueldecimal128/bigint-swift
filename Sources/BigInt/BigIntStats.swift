enum BigIntStats {
    nonisolated(unsafe) static var BI_OP_COUNTS = [Int64](repeating: 0, count: StatsOp.CARDINALITY)
    // snapshot()/Snapshot/Interval deferred to Phase 4 (Monotonic clock + Regex).
}

/// Increment helper (Kotlin `++BI_OP_COUNTS[op.ordinal]`).
@inline(__always)
func biStat(_ op: StatsOp) {
    BigIntStats.BI_OP_COUNTS[op.ordinal] += 1
}
